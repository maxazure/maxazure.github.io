import assert from 'node:assert/strict';
import { advanceDemo, initialDemo } from '../src/lib/crm-demo.ts';
const notes = ['Original brief', 'Colleague adds review', 'Reviewed merge keeps both changes'];
const empty = initialDemo();
const created = advanceDemo(empty, notes);
const replay = advanceDemo(created, notes);
assert.equal(replay.note.id, created.note.id);
assert.deepEqual(replay.revisions, created.revisions, 'A retry must not create a revision');
const edited = advanceDemo(replay, notes);
const rejected = advanceDemo(edited, notes);
assert.deepEqual(rejected.note, edited.note, 'A stale update must preserve the accepted content');
assert.deepEqual(rejected.revisions, edited.revisions);
const merged = advanceDemo(rejected, notes);
assert.equal(merged.note.version, 3);
assert.equal(merged.note.text, notes[2]);
assert.deepEqual(merged.revisions.map(note => note.text), notes, 'Earlier content must remain readable');
assert.equal(advanceDemo(merged, notes), merged, 'Completion must not add writes');
assert.deepEqual(empty, initialDemo(), 'Actions must not mutate earlier state');
assert.equal(initialDemo().revisions.length, 0, 'Reset must discard local demo data');
console.log('CRM demo: retry, stale-write preservation, revision history and reset pass');
